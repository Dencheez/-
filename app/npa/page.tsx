export default function NPAPage() {
    // Логика пагинации
    const [currentPage, setCurrentPage] = useState(1);
    const itemsPerPage = 10; // по сколько штук выводить

    const totalPages = Math.ceil(npaList.length / itemsPerPage);
    const indexOfLastItem = currentPage * itemsPerPage;
    const indexOfFirstItem = indexOfLastItem - itemsPerPage;
    const currentItems = npaList.slice(indexOfFirstItem, indexOfLastItem);

    const paginate = (pageNumber: number) => {
        setCurrentPage(pageNumber);
        window.scrollTo({ top: 0, behavior: 'smooth' }); // скролл вверх при смене страницы
    };

    return (
        <AppShell>
            <main className="bg-white">
                <div className="max-w-6xl mx-auto px-4 md:px-2">
                    {/* Заголовок */}
                    <div className="flex flex-col md:flex-row justify-between items-start md:items-end border-b-2 border-slate-100 pb-8 mb-10 gap-6">
                        <h1 className="text-4xl md:text-5xl font-black text-slate-900 tracking-tighter uppercase leading-none">
                            НПА
                        </h1>
                    </div>

                    <h2 className="text-2xl font-black text-[#00B5C4] mb-12 uppercase tracking-tight">
                        Действующие НПА на 2023 год
                    </h2>

                    {/* Список документов (теперь только текущие 10 штук) */}
                    <div className="grid gap-10 min-h-[600px]">
                        {currentItems.map((npa, index) => (
                            <React.Fragment key={index}>
                                {npa.link ? (
                                    <Link href={npa.link} target="_blank" rel="noopener noreferrer">
                                        <article className="border-l-4 border-slate-100 pl-6 cursor-pointer hover:border-[#00B5C4] transition-all group">
                                            <h3 className="text-xl font-black text-slate-800 leading-tight group-hover:text-[#00B5C4]">
                                                {npa.title}
                                            </h3>
                                            <p className="text-slate-500 mt-2 font-medium">{npa.desc}</p>
                                        </article>
                                    </Link>
                                ) : (
                                    <article className="border-l-4 border-slate-100 pl-6 cursor-default">
                                        <h3 className="text-xl font-black text-slate-800 leading-tight">
                                            {npa.title}
                                        </h3>
                                        <p className="text-slate-500 mt-2 font-medium">{npa.desc}</p>
                                    </article>
                                )}
                            </React.Fragment>
                        ))}
                    </div>

                    {/* ПАГИНАЦИЯ */}
                    <div className="mt-20 flex items-center justify-center gap-2">
                        <button
                            onClick={() => currentPage > 1 && paginate(currentPage - 1)}
                            disabled={currentPage === 1}
                            className="p-2 rounded-lg border border-slate-200 disabled:opacity-30 hover:bg-slate-50 transition-colors"
                        >
                            <ChevronLeft className="w-6 h-6" />
                        </button>

                        <div className="flex gap-2">
                            {Array.from({ length: totalPages }, (_, i) => i + 1).map((number) => (
                                <button
                                    key={number}
                                    onClick={() => paginate(number)}
                                    className={`w-12 h-12 rounded-xl font-black transition-all ${currentPage === number
                                        ? "bg-[#00B5C4] text-white shadow-lg shadow-cyan-500/30"
                                        : "bg-white border border-slate-200 text-slate-400 hover:border-[#00B5C4] hover:text-[#00B5C4]"
                                        }`}
                                >
                                    {number}
                                </button>
                            ))}
                        </div>

                        <button
                            onClick={() => currentPage < totalPages && paginate(currentPage + 1)}
                            disabled={currentPage === totalPages}
                            className="p-2 rounded-lg border border-slate-200 disabled:opacity-30 hover:bg-slate-50 transition-colors"
                        >
                            <ChevronRight className="w-6 h-6" />
                        </button>
                    </div>
                </div>
            </main>
        </AppShell>
    )
}